/// `Locale.getDisplayScript(Locale)`: oxjvm stores no script, so this is empty.
pub(crate) fn locale_display_script(vm: &mut Vm<'_>, _args: &[Value]) -> Result<Value, VmError> {
    object(vm.make_string("")?)
}

