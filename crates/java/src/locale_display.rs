//! Localized display names for `java.util.Locale`: `getDisplayLanguage`,
//! `getDisplayCountry`, `getDisplayVariant`, `getDisplayName`, and
//! `getDisplayScript`, resolved against a target locale.

use alloc::string::{String, ToString};

use oxjvm_vm::{ObjectRef, Value, Vm, VmError};

use crate::{object, receiver, ref_arg};

/// The target locale's language, or the default locale's language when the
/// caller passed no explicit target.
fn target_language(vm: &mut Vm<'_>, target: ObjectRef) -> Result<String, VmError> {
    let locale = if target.is_null() {
        let class = vm.resolve_class("java/util/Locale")?;
        let (declaring, method) = vm
            .find_method(class, "getDefault", "()Ljava/util/Locale;")
            .ok_or_else(|| VmError::internal("Locale.getDefault"))?;
        vm.invoke_method(declaring, method, alloc::vec::Vec::new())?
            .as_ref()
    } else {
        target
    };
    Ok(vm
        .read_string_field(locale, vm.class_of(locale), "language")
        .unwrap_or_default()
        .to_lowercase())
}

fn lookup_lang(target: &str, code: &str) -> Option<&'static str> {
    DISPLAY_LANG
        .iter()
        .find(|(t, c, _)| *t == target && *c == code)
        .map(|(_, _, n)| *n)
}

fn lookup_ctry(target: &str, code: &str) -> Option<&'static str> {
    DISPLAY_CTRY
        .iter()
        .find(|(t, c, _)| *t == target && *c == code)
        .map(|(_, _, n)| *n)
}

/// The localized language name, falling back to English then the raw code.
pub(crate) fn display_language(
    vm: &mut Vm<'_>,
    this: ObjectRef,
    target: ObjectRef,
) -> Result<String, VmError> {
    let code = vm
        .read_string_field(this, vm.class_of(this), "language")
        .unwrap_or_default();
    if code.is_empty() {
        return Ok(String::new());
    }
    let t = target_language(vm, target)?;
    Ok(lookup_lang(&t, &code)
        .or_else(|| lookup_lang("en", &code))
        .unwrap_or(&code)
        .to_string())
}

/// The localized country name, falling back to English then the raw code.
pub(crate) fn display_country(
    vm: &mut Vm<'_>,
    this: ObjectRef,
    target: ObjectRef,
) -> Result<String, VmError> {
    let code = vm
        .read_string_field(this, vm.class_of(this), "country")
        .unwrap_or_default();
    if code.is_empty() {
        return Ok(String::new());
    }
    let t = target_language(vm, target)?;
    Ok(lookup_ctry(&t, &code)
        .or_else(|| lookup_ctry("en", &code))
        .unwrap_or(&code)
        .to_string())
}

/// The localized variant name (empty when unknown).
pub(crate) fn display_variant(
    vm: &mut Vm<'_>,
    this: ObjectRef,
    target: ObjectRef,
) -> Result<String, VmError> {
    let code = vm
        .read_string_field(this, vm.class_of(this), "variant")
        .unwrap_or_default();
    if code.is_empty() {
        return Ok(String::new());
    }
    let t = target_language(vm, target)?;
    // The JDK shows a localized variant name when one exists for the target
    // language, and otherwise the variant code itself (never an English fallback).
    Ok(DISPLAY_VARIANT
        .iter()
        .find(|(tl, v, _)| *tl == t && *v == code)
        .map(|(_, _, n)| (*n).to_string())
        .unwrap_or_else(|| code.clone()))
}

/// Compose a full display name: `language (country, variant)`.
pub(crate) fn display_name(
    vm: &mut Vm<'_>,
    this: ObjectRef,
    target: ObjectRef,
) -> Result<String, VmError> {
    let language = display_language(vm, this, target)?;
    let country = display_country(vm, this, target)?;
    let variant = display_variant(vm, this, target)?;
    let suffix = match (country.is_empty(), variant.is_empty()) {
        (true, true) => String::new(),
        (false, true) => country,
        (true, false) => variant,
        (false, false) => alloc::format!("{country}, {variant}"),
    };
    let text = if language.is_empty() {
        suffix
    } else if suffix.is_empty() {
        language
    } else {
        alloc::format!("{language} ({suffix})")
    };
    Ok(text)
}

/// `Locale.getDisplayLanguage(Locale)`.
pub(crate) fn locale_display_language(
    vm: &mut Vm<'_>,
    args: &[Value],
    with_target: bool,
) -> Result<Value, VmError> {
    let target = if with_target {
        ref_arg(args, 1)
    } else {
        ObjectRef::NULL
    };
    let text = display_language(vm, receiver(args), target)?;
    object(vm.make_string(&text)?)
}

